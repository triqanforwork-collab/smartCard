    private void formComponentShown(java.awt.event.ComponentEvent evt) {//GEN-FIRST:event_formComponentShown
        if (app.admin == null) {
            app.go(MainFrame.CONNECT);
            return;
        }

        LocalDate today = LocalDate.now();
        javax.swing.table.DefaultTableModel m = model("Sắp hết hạn: Mã HV", "Họ tên", "SĐT", "Gói tập", "Hạn gói", "Còn (ngày)");
        try {
            Database.Stats s = app.db.stats(today);
            txtAdmin.setText(app.admin);
            txtMembers.setText(s.members() + "  (" + s.active() + " / " + s.expired() + ")");
            txtExpiring.setText(String.valueOf(s.expiringSoon()));
            txtTopUp.setText(String.valueOf(s.topUpThisMonth()));
            txtCheckIns.setText(String.valueOf(s.checkInsToday()));
            txtWarnings.setText(String.valueOf(s.warningsToday()));
            for (MemberInfo h : app.db.expiringWithin(7, today)) {
                m.addRow(new Object[]{h.maHV, h.hoTen, h.sdt, h.goiTap, h.hanGoi,
                        ChronoUnit.DAYS.between(today, Database.expiry(h.hanGoi))});
            }
        } catch (Exception e) {
            app.error(e);
        }
        tblExpiring.setModel(m);
    }//GEN-LAST:event_formComponentShown

