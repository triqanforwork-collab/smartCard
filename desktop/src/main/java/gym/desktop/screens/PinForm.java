    private void btnBackActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBackActionPerformed
        txtPin.setText("");
        app.member = null;
        app.card.disconnect();
        app.go(MainFrame.CONNECT);
    }//GEN-LAST:event_btnBackActionPerformed

    private void btnKhoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnKhoaActionPerformed
        try {
            app.requireAdmin();   // mở khóa, đặt lại PIN là việc của Admin
            app.go(MainFrame.UNBLOCK);
        } catch (Exception e) {
            app.error(e);
        }
    }//GEN-LAST:event_btnKhoaActionPerformed

    private void btnXacNhanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXacNhanActionPerformed
        try {
            String pin = Input.pin(txtPin, null, "Mã PIN");
            // Nhập PIN, kiểm tra thẻ đã báo mất, kiểm tra thẻ thật bằng chữ ký RSA (xem MemberService.login)
            app.member = app.members.login(pin);
            // Đối chiếu số dư trên thẻ với CSDL; lệch thì cảnh báo (đã ghi nhật ký)
            String warning = app.members.reconcile(app.member.maHV);
            if (warning != null) {
                JOptionPane.showMessageDialog(this, warning, "Cảnh báo đối chiếu số dư", JOptionPane.WARNING_MESSAGE);
            }
            app.go(MainFrame.INFO);
        } catch (Exception e) {
            app.error(e);
            if (!app.card.isConnected()) app.go(MainFrame.CONNECT); // thẻ giả / đã báo mất: đã bị ngắt kết nối
        } finally {
            txtPin.setText("");
        }
    }//GEN-LAST:event_btnXacNhanActionPerformed


