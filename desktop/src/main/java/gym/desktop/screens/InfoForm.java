    private void formComponentShown(java.awt.event.ComponentEvent evt) {//GEN-FIRST:event_formComponentShown
        fill(new MemberInfo());   // xoá dữ liệu cũ trước khi đọc thẻ
        txtBalance.setText("");
        MainFrame.showPhoto(lblPhoto, null);
        newPhoto = null;
        try {
            app.member = app.card.getInfo();
            fill(app.member);
            txtBalance.setText(String.valueOf(app.wallet.balance().balance()));
            MainFrame.showPhoto(lblPhoto, app.card.getPhoto());
        } catch (Exception e) {
            app.error(e);
        }
    }//GEN-LAST:event_formComponentShown

    private void btnPhotoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPhotoActionPerformed
        try {
            byte[] b = MainFrame.chooseImage(this);
            if (b != null) {
                newPhoto = b;
                MainFrame.showPhoto(lblPhoto, b);
            }
        } catch (Exception e) {
            app.error(e);
        }
    }//GEN-LAST:event_btnPhotoActionPerformed

