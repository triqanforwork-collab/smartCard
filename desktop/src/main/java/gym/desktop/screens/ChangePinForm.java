    private void btnChangeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnChangeActionPerformed
        try {
            String oldPin = Input.pin(txtOldPin, null, "PIN hiện tại");
            String newPin = Input.pin(txtNewPin, txtNewPin2, "PIN mới");
            if (newPin.equals(oldPin)) throw new IllegalArgumentException("PIN mới phải khác PIN hiện tại");
            app.members.changePin(app.member == null ? null : app.member.maHV, oldPin, newPin);
            JOptionPane.showMessageDialog(this, "Đã đổi mã PIN");
            app.go(MainFrame.INFO);
        } catch (Exception e) {
            app.error(e);
        } finally {
            txtOldPin.setText("");
            txtNewPin.setText("");
            txtNewPin2.setText("");
        }
    }//GEN-LAST:event_btnChangeActionPerformed


