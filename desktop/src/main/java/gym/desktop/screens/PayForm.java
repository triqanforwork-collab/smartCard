    private void btnPayActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPayActionPerformed
        try {
            int i = cboPackage.getSelectedIndex();
            if (i < 0) throw new IllegalArgumentException("Chưa chọn gói tập");
            Database.GymPackage pkg = packages.get(i);
            if (JOptionPane.showConfirmDialog(this, "Thanh toán " + pkg.price() + " nghìn đồng cho " + pkg.name() + "?",
                    "Xác nhận", JOptionPane.YES_NO_OPTION) != JOptionPane.YES_OPTION) return;
            app.member = app.wallet.payPackage(app.member, pkg);
            refresh();
            JOptionPane.showMessageDialog(this, "Đã gia hạn " + pkg.name() + ". Hạn mới: " + app.member.hanGoi);
        } catch (Exception e) {
            app.error(e);
        }
    }//GEN-LAST:event_btnPayActionPerformed

    private void refresh() {
        if (app.member == null) return;
        txtMember.setText(app.member.maHV + " – " + app.member.hoTen);
        txtCurPackage.setText(app.member.goiTap);
        txtExpiry.setText(app.member.hanGoi);
        try {
            txtBalance.setText(String.valueOf(app.wallet.balance().balance()));
            packages = app.db.packages();   // chỉ các gói đang bán
            cboPackage.removeAllItems();
            for (Database.GymPackage p : packages) cboPackage.addItem(p.toString());
        } catch (Exception e) {
            app.error(e);
        }
    }


