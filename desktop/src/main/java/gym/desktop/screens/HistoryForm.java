    private void formComponentShown(java.awt.event.ComponentEvent evt) {//GEN-FIRST:event_formComponentShown
        boolean all = app.member == null;
        if (all && app.admin == null) {   // lịch sử của mọi người chỉ Admin được xem
            app.go(MainFrame.CONNECT);
            return;
        }
        txtMember.setText(all ? "Tất cả hội viên" : app.member.maHV + " – " + app.member.hoTen);
        javax.swing.table.DefaultTableModel m = model("Thời gian", "Mã HV", "Loại", "Số tiền", "Số dư sau", "GD số", "Nội dung", "Chữ ký");
        try {
            for (Database.Transaction t : app.db.transactions(all ? "" : app.member.maHV)) {
                m.addRow(new Object[]{t.time(), t.maHV(), t.type(), t.amount(), t.balanceAfter(), t.txCount(), t.note(),
                        t.verified() ? "Hợp lệ" : "Sai"});
            }
        } catch (Exception e) {
            app.error(e);
        }
        tblHistory.setModel(m);
    }//GEN-LAST:event_formComponentShown

    private void btnBackActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBackActionPerformed
        app.go(app.member != null ? MainFrame.INFO : MainFrame.MEMBERS);
    }//GEN-LAST:event_btnBackActionPerformed

    /** Bảng chỉ để xem, không cho sửa ô. */
    private static javax.swing.table.DefaultTableModel model(String... columns) {
        return new javax.swing.table.DefaultTableModel(columns, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
    }


