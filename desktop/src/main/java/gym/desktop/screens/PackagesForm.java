    private void btnToggleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnToggleActionPerformed
        try {
            app.requireAdmin();
            Database.GymPackage p = selected();
            app.db.setPackageActive(p.id(), !p.active());
            app.db.log(null, p.active() ? "Ngừng bán gói" : "Mở bán gói", p.name(), false);
            load();
        } catch (Exception e) {
            app.error(e);
        }
    }//GEN-LAST:event_btnToggleActionPerformed

    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        try {
            app.requireAdmin();
            Database.GymPackage p = selected();
            app.db.updatePackage(p.id(), name(), months(), price());
            app.db.log(null, "Sửa gói tập", p.name() + " → " + name() + ", " + months() + " tháng, " + price(), false);
            load();
        } catch (Exception e) {
            app.error(e);
        }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        try {
            app.requireAdmin();
            app.db.addPackage(name(), months(), price());
            app.db.log(null, "Thêm gói tập", name() + ", " + months() + " tháng, " + price(), false);
            load();
        } catch (Exception e) {
            app.error(e);
        }
    }//GEN-LAST:event_btnAddActionPerformed

    /** Bảng chỉ để xem, không cho sửa ô. */
    private static javax.swing.table.DefaultTableModel model(String... columns) {
        return new javax.swing.table.DefaultTableModel(columns, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
    }

    private void load() {
        javax.swing.table.DefaultTableModel m = model("Mã", "Tên gói", "Số tháng", "Giá (nghìn đồng)", "Trạng thái");
        try {
            rows = app.db.allPackages();
            for (Database.GymPackage p : rows) {
                m.addRow(new Object[]{p.id(), p.name(), p.months(), p.price(), p.active() ? "Đang bán" : "Ngừng bán"});
            }
        } catch (Exception e) {
            app.error(e);
        }
        tblPackages.setModel(m);
    }

    private Database.GymPackage selected() {
        int i = tblPackages.getSelectedRow();
        if (i < 0) throw new IllegalArgumentException("Chọn một gói trong bảng trước");
        return rows.get(tblPackages.convertRowIndexToModel(i));
    }

    private String name() {
        String s = txtName.getText().trim();
        if (s.isEmpty() || s.length() > 40) throw new IllegalArgumentException("Tên gói dài 1–40 ký tự");
        return s;
    }

    private int months() {
        String s = txtMonths.getText().trim();
        if (!s.matches("\\d{1,2}") || Integer.parseInt(s) < 1 || Integer.parseInt(s) > 36) {
            throw new IllegalArgumentException("Số tháng là số nguyên từ 1 đến 36");
        }
        return Integer.parseInt(s);
    }

    private long price() {
        return Input.amount(txtPrice);
    }


