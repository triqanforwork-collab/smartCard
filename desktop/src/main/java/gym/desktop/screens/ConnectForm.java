    private void btnConnectActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConnectActionPerformed
        try {
            String r = (String) cboReader.getSelectedItem();
            if (r == null) throw new Exception("Chưa có đầu đọc để kết nối");
            app.card.connect(r);
            if (app.card.isInitialized()) {
                if (app.reissue != null) {
                    app.card.disconnect();
                    throw new IllegalStateException("Để cấp lại thẻ cho " + app.reissue.maHV + ", hãy cắm một thẻ trắng.");
                }
                app.go(MainFrame.PIN);
            } else if (app.admin != null) {
                app.go(MainFrame.INIT);
            } else {
                app.card.disconnect();
                throw new IllegalStateException("Đây là thẻ trắng. Admin cần đăng nhập để phát hành thẻ.");
            }
        } catch (Exception e) {
            app.error(e);
        }
    }//GEN-LAST:event_btnConnectActionPerformed

    private void refresh() {
        cboReader.removeAllItems();
        for (String r : CardService.readers()) cboReader.addItem(r);
        String s = cboReader.getItemCount() == 0
                ? "Không thấy đầu đọc nào. Hãy bấm Run trong JCIDE (đã tick Enable PCSC Interface) rồi bấm Làm mới."
                : "Chọn đầu đọc của JCIDE rồi bấm Kết nối.";
        if (app.admin != null) s += "   Admin đang đăng nhập: " + app.admin;
        if (app.reissue != null) s += "   Đang cấp lại thẻ cho " + app.reissue.maHV + ": cắm thẻ trắng rồi bấm Kết nối.";
        lblStatus.setText(s);
    }


