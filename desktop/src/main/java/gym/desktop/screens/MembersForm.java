    /** Bảng chỉ để xem, không cho sửa ô. */
    private static javax.swing.table.DefaultTableModel model(String... columns) {
        return new javax.swing.table.DefaultTableModel(columns, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
    }

    private void search() {
        javax.swing.table.DefaultTableModel m = model("Mã HV", "Họ tên", "SĐT", "Gói tập", "Hạn gói", "Hạn", "Thẻ", "Thẻ số", "Lượt tập");
        try {
            rows = app.db.members(txtSearch.getText());
            for (Database.Member r : rows) {
                m.addRow(new Object[]{r.info().maHV, r.info().hoTen, r.info().sdt, r.info().goiTap, r.info().hanGoi,
                        status(r.info().hanGoi), r.status(), r.cardNo(), r.checkins()});
            }
        } catch (Exception e) {
            app.error(e);
        }
        tblMembers.setModel(m);
    }

    private Database.Member selected() {
        int i = tblMembers.getSelectedRow();
        if (i < 0) throw new IllegalArgumentException("Chọn một hội viên trong bảng trước");
        return rows.get(tblMembers.convertRowIndexToModel(i));
    }

    private static String status(String expiry) {
        LocalDate e = Database.expiry(expiry);
        return e == null ? "Chưa có gói" : e.isBefore(LocalDate.now()) ? "Hết hạn" : "Còn hạn";
    }


