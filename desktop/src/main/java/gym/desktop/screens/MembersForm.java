    private void btnLostActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLostActionPerformed
        try {
            app.requireAdmin();
            Database.Member r = selected();
            if (!Database.ACTIVE.equals(r.status())) throw new IllegalStateException("Thẻ của " + r.info().maHV + " đã được báo mất trước đó");
            if (JOptionPane.showConfirmDialog(this, "Báo mất thẻ của " + r.info().maHV + " – " + r.info().hoTen
                    + "?\nThẻ này sẽ không dùng được nữa.", "Xác nhận", JOptionPane.YES_NO_OPTION) != JOptionPane.YES_OPTION) return;
            app.db.reportLost(r.info().maHV);
            app.db.log(r.info().maHV, "Báo mất thẻ", "Thẻ số " + r.cardNo(), true);
            search();
        } catch (Exception e) {
            app.error(e);
        }
    }//GEN-LAST:event_btnLostActionPerformed

    private void btnReissueActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnReissueActionPerformed
        try {
            app.requireAdmin();
            Database.Member r = selected();
            if (!Database.LOST.equals(r.status())) throw new IllegalStateException("Chỉ cấp lại thẻ cho hội viên đã báo mất thẻ");
            app.reissue = r.info();
            JOptionPane.showMessageDialog(this, "Cắm một thẻ trắng vào đầu đọc rồi bấm Kết nối để cấp lại thẻ cho " + r.info().maHV + ".");
            app.go(MainFrame.CONNECT);
        } catch (Exception e) {
            app.error(e);
        }
    }//GEN-LAST:event_btnReissueActionPerformed

