    private void btnChangeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnChangeActionPerformed
        try {
            app.requireAdmin();
            char[] old = txtOld.getPassword(), pass = txtNew.getPassword();
            if (pass.length < 6) throw new IllegalArgumentException("Mật khẩu mới phải có ít nhất 6 ký tự");
            if (!java.util.Arrays.equals(pass, txtNew2.getPassword())) throw new IllegalArgumentException("Hai ô mật khẩu mới không khớp nhau");
            if (java.util.Arrays.equals(pass, old)) throw new IllegalArgumentException("Mật khẩu mới phải khác mật khẩu hiện tại");
            if (!app.db.changeAdminPassword(app.admin, old, pass)) {
                app.db.log(null, "Đổi mật khẩu Admin thất bại", "Sai mật khẩu hiện tại", true);
                throw new IllegalArgumentException("Mật khẩu hiện tại không đúng");
            }
            app.db.log(null, "Đổi mật khẩu Admin", null, false);
            JOptionPane.showMessageDialog(this, "Đã đổi mật khẩu Admin");
            app.go(MainFrame.ADMIN_HOME);
        } catch (Exception e) {
            app.error(e);
        } finally {
            txtOld.setText("");
            txtNew.setText("");
            txtNew2.setText("");
        }
    }//GEN-LAST:event_btnChangeActionPerformed


