    /** Bảng chỉ để xem, không cho sửa ô. */
    private static javax.swing.table.DefaultTableModel model(String... columns) {
        return new javax.swing.table.DefaultTableModel(columns, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
    }

    private void load() {
        if (app.admin == null) return;
        javax.swing.table.DefaultTableModel m = model("Thời gian", "Admin", "Mã HV", "Hoạt động", "Chi tiết", "Mức");
        try {
            for (Database.LogEntry l : app.db.logs(cboFilter.getSelectedIndex() == 1)) {
                m.addRow(new Object[]{l.time(), l.admin(), l.maHV(), l.action(), l.detail(), l.warning() ? "CẢNH BÁO" : ""});
            }
        } catch (Exception e) {
            app.error(e);
        }
        tblLogs.setModel(m);
    }


