    private void btnTopUpActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTopUpActionPerformed
        try {
            app.requireAdmin();
            long amount = Input.amount(txtAmount);
            String adminPin = Input.pin(txtAdminPin, null, "PIN Admin");
            CardService.TxResult r = app.wallet.topUp(app.member.maHV, amount, adminPin, app::askSecret);
            txtAmount.setText("");
            refresh();
            JOptionPane.showMessageDialog(this, "Đã nạp " + amount + " nghìn đồng. Số dư: " + r.balance()
                    + " nghìn đồng.\nChữ ký RSA của giao dịch hợp lệ, đã ghi vào CSDL.");
        } catch (Exception e) {
            app.error(e);
        } finally {
            txtAdminPin.setText("");
        }
    }//GEN-LAST:event_btnTopUpActionPerformed

    private void refresh() {
        txtMember.setText(app.member == null ? "" : app.member.maHV + " – " + app.member.hoTen);
        try {
            txtBalance.setText(String.valueOf(app.wallet.balance().balance()));
        } catch (Exception e) {
            txtBalance.setText("");
            app.error(e);
        }
    }


