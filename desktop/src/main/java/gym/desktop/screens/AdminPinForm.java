    private void btnForgotActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnForgotActionPerformed
        try {
            app.requireAdmin();
            String pin = Input.pin(txtNew, txtNew2, "PIN Admin mới");
            javax.swing.JTextField code = new javax.swing.JTextField(16);
            Object[] form = {"Nhập mã khôi phục của tài khoản " + app.admin + ":", code,
                    "Thẻ phát hành trước đây vẫn mang PIN Admin cũ; không nhớ PIN cũ thì các thẻ đó cần Đổi thẻ hỏng."};
            if (JOptionPane.showConfirmDialog(this, form, "Quên PIN Admin", JOptionPane.OK_CANCEL_OPTION,
                    JOptionPane.PLAIN_MESSAGE) != JOptionPane.OK_OPTION) return;
            if (!app.db.checkRecoveryCode(app.admin, code.getText())) {
                app.db.log(null, "Đặt lại PIN Admin thất bại", "Sai mã khôi phục", true);
                throw new IllegalArgumentException("Mã khôi phục không đúng");
            }
            int ver = app.db.setAdminPin(pin);
            app.db.log(null, "Đặt lại PIN Admin bằng mã khôi phục", "Phiên bản " + ver, true);
            JOptionPane.showMessageDialog(this, "Đã đặt PIN Admin mới (phiên bản " + ver + "). Mã khôi phục cũ hết hiệu lực.");
            app.showRecoveryCode(app.admin, app.db.newRecoveryCode(app.admin));
            refresh();
        } catch (Exception e) {
            app.error(e);
        } finally {
            clear();
        }
    }//GEN-LAST:event_btnForgotActionPerformed

    private void btnChangeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnChangeActionPerformed
        try {
            app.requireAdmin();
            int cur = app.db.adminPinVersion();
            String pin = Input.pin(txtNew, txtNew2, "PIN Admin mới");
            if (cur > 0) {
                String old = Input.pin(txtOld, null, "PIN Admin hiện tại");
                if (old.equals(pin)) throw new IllegalArgumentException("PIN Admin mới phải khác PIN hiện tại");
                if (!app.db.checkAdminPin(old, cur)) {
                    app.db.log(null, "Đổi PIN Admin thất bại", "Sai PIN Admin hiện tại", true);
                    throw new IllegalArgumentException("PIN Admin hiện tại không đúng");
                }
            }
            int ver = app.db.setAdminPin(pin);
            app.db.log(null, "Đổi PIN Admin", "Phiên bản " + ver, false);
            JOptionPane.showMessageDialog(this, "Đã đổi PIN Admin (phiên bản " + ver + ").\n"
                    + "Thẻ phát hành trước đó sẽ được cập nhật khi Admin thao tác với thẻ (phần mềm hỏi PIN cũ một lần).");
            refresh();
        } catch (Exception e) {
            app.error(e);
        } finally {
            clear();
        }
    }//GEN-LAST:event_btnChangeActionPerformed

    private void refresh() {
        try {
            int v = app.db.adminPinVersion();
            txtOld.setEnabled(v > 0);
            lblStatus.setText(v == 0 ? "Phòng gym chưa có PIN Admin: nhập PIN mới 2 lần rồi bấm Đổi PIN Admin."
                    : "PIN Admin đang dùng: phiên bản " + v + ". Mọi thẻ phát hành từ nay dùng PIN này.");
        } catch (Exception e) {
            app.error(e);
        }
    }

    private void clear() {
        txtOld.setText("");
        txtNew.setText("");
        txtNew2.setText("");
    }


